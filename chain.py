"""Sound logic for Mic Control: settings, the plugin library, and the Equalizer APO config it writes.

Signal flow (mic):  boost -> rumble cut -> AI noise removal (RNNoise) -> gate (ReaGate)
                    -> tone EQ (Equalizer APO's own filters) -> warmth (TDR SlickEQ "Deep" stage)
                    -> de-esser (TDR Nova)
                    -> compressor (TDR Kotelnikov) -> effects rack -> limiter (LoudMax)
Guitar (Input 2):   boost -> low cut -> gate -> amp-style EQ -> sustain (Kotelnikov) -> effects rack,
                    then mixed with the voice before the limiter.

Everything runs on one channel and is copied to both sides at the end, so each plugin works once.
Plugins that keep their state in a "chunk" get it generated by our own VST host (vsthost.py), because
Equalizer APO ignores parameter names for them; the others get parameter names.
"""

