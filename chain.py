def builtin_guitar_presets(lib):
    def slot(uid, pid, **values):
        """values in real units as the plugin shows them (%, s, ms, dB) or a choice's text."""
        if not lib.has(pid):
            return {"uid": uid, "plugin": pid, "on": True, "values": {}}
        known = lib.plugins[pid]["byname"]
        out = {}
        for k, v in values.items():
            name = k if k in known else k.replace("_", " ")  # "Delay_Ms" is a real name, "Dry_Level" is "Dry Level"
            out[name] = lib.norm(pid, name, v)
        return {"uid": uid, "plugin": pid, "on": True, "values": out}

