# ----------------------------------------------------------------------------- plugin library
class Library:
    """The bundled plugins: their controls (from catalog.json) and how to put them in the config."""

    def __init__(self, catalog_file=CATALOG_FILE):
        try:
            self.plugins = json.loads(Path(catalog_file).read_text(encoding="utf-8"))
        except (OSError, ValueError):
            self.plugins = {}
        self.hosts = {}       # plugin id -> loaded VST instance, only for chunk-based plugins
        self.chunk_cache = {}  # (plugin id, values) -> base64 chunk
        self.failures = []     # plugins that couldn't produce their state (logged by the server)
        self.disabled = set()  # plugin ids switched off after crashing the audio service (settings keep them)
        # plugin files actually present (tools/get_plugins.py fetches them); a missing one is simply skipped
        self.files = {f.name for f in Path(catalog_file).parent.glob("*.dll")}
        for p in self.plugins.values():
            p["byname"] = {q["name"]: q for q in p["params"]}
            for q in p["params"]:
                if q["kind"] == "number":
                    q["nums"] = [_num(s) for s in q["shown"]]

    def public(self):
        """Catalog for the UI (without the lookup helpers)."""
        out = {}
        for pid, p in self.plugins.items():
            out[pid] = {k: v for k, v in p.items() if k != "byname"}
            out[pid]["params"] = [{k: v for k, v in q.items() if k != "nums"} for q in p["params"]]
            out[pid]["installed"] = p["file"] in self.files
        return out

    def has(self, pid):
        return pid in self.plugins

    def usable(self, pid):
        """Installed and not switched off by the crash guard: whether the config may load it."""
        return pid in self.plugins and pid not in self.disabled and self.plugins[pid]["file"] in self.files

    def has_file(self, name):
        return name in self.files

    def pid_for_file(self, name):
        name = name.lower()
        return next((pid for pid, p in self.plugins.items() if p["file"].lower() == name), None)

    def norm(self, pid, name, value):
        """Real value (dB, ms, Hz, or a choice's text) -> the plugin's 0..1 position."""
        q = self.plugins[pid]["byname"][name]
        if q["kind"] == "choice":
            for c in q["choices"]:
                if c["text"].lower().startswith(str(value).lower()):
                    return c["value"]
            raise KeyError(f"{pid}.{name} has no choice {value!r}")
        nums = q["nums"]
        steps = len(nums) - 1
        for k in range(steps):
            a, b = nums[k], nums[k + 1]
            if a is None or b is None:
                continue
            if min(a, b) <= value <= max(a, b):
                t = 0 if a == b else (value - a) / (b - a)
                return (k + t) / steps
        # outside the plugin's range: nearest end
        valid = [(k, v) for k, v in enumerate(nums) if v is not None]
        k, _ = min(valid, key=lambda kv: abs(kv[1] - value))
        return k / steps

    def line(self, pid, values, plugin_dir):
        """Config line for one plugin. values = {parameter name: 0..1}; unset ones use the defaults."""
        p = self.plugins[pid]
        full = {q["name"]: q["default"] for q in p["params"]}
        full.update({k: v for k, v in values.items() if k in full})
        dll = Path(plugin_dir) / p["file"]
        names = f'VSTPlugin: Library "{dll}" ' + " ".join(f'"{name}" {value:.6f}' for name, value in full.items())
        if p["route"] == "names":
            return names
        try:
            return f'VSTPlugin: Library "{dll}" ChunkData "{self.chunk(pid, full)}"'
        except OSError as e:
            # A plugin that misbehaves in our host (ctypes reports access violations as OSError) must not
            # take the app down: drop that host and fall back to the plugin's own defaults in the config.
            self.hosts.pop(pid, None)
            self.failures.append(f"{p['name']}: {e}")
            return f'VSTPlugin: Library "{dll}"'

    def chunk(self, pid, full):
        key = (pid, json.dumps(full, sort_keys=True))
        if key not in self.chunk_cache:
            host = self.hosts.get(pid)
            if host is None:
                from vsthost import Plugin  # loaded only when a chunk-based plugin is used
                host = self.hosts[pid] = Plugin(str(APP_DIR / "plugins" / self.plugins[pid]["file"]))
            for q in self.plugins[pid]["params"]:
                host.set(q["index"], float(full[q["name"]]))
            data = host.chunk()
            if not data:
                raise OSError(f"{pid} returned an empty state")
            if len(self.chunk_cache) > 400:
                self.chunk_cache.clear()
            self.chunk_cache[key] = base64.b64encode(data).decode()
        return self.chunk_cache[key]

    def latency_ms(self, pid, rate=48000):
        return self.plugins[pid]["latency"] / rate * 1000


def _num(text):
    if "inf" in text.lower() or text.strip().lower() == "off":
        return None
    m = NUM.search(text.replace(",", "."))
    return float(m.group()) if m else None


# ----------------------------------------------------------------------------- settings
def _clamp_number(src, lo, hi):
    try:
        v = float(src)
    except (TypeError, ValueError):
        return None
    if v != v:
        return None
    return round(min(hi, max(lo, v)), 2)


def sanitize_rack(raw, lib):
    """A rack is a list of {uid, plugin, on, values: {parameter name: 0..1}} for known plugins."""
    rack, seen = [], set()
    for slot in raw if isinstance(raw, list) else []:
        if not isinstance(slot, dict) or not isinstance(slot.get("plugin"), str) or not lib.has(slot["plugin"]) \
                or not lib.plugins[slot["plugin"]].get("rack", True):
            continue
        known = lib.plugins[slot["plugin"]]["byname"]
        values = {}
        raw_values = slot.get("values") if isinstance(slot.get("values"), dict) else {}
        for name, v in raw_values.items():
            n = _clamp_number(v, 0, 1)
            if name in known and n is not None:
                values[name] = n
        uid = re.sub(r"[^a-zA-Z0-9-]", "", str(slot.get("uid") or ""))[:24] or "fx"
        while uid in seen:  # the UI finds slots by uid, so they must be unique
            uid = f"{uid[:20]}-{len(seen)}"
        seen.add(uid)
        rack.append({"uid": uid, "plugin": slot["plugin"], "on": bool(slot.get("on", True)), "values": values})
        if len(rack) >= MAX_RACK:
            break
    return rack


def migrate(raw, lib):
    """Older settings (version 1): ReaComp compressor/limiter keep their numbers on the new plugins,
    and the old built-in reverb/delay become rack effects."""
    if not isinstance(raw, dict) or raw.get("version", 1) >= 2:
        return raw
    raw = copy.deepcopy(raw)
    raw["version"] = 2

    def to_rack(rack_key, holder, reverb, delay):
        rack = holder.setdefault(rack_key, [])
        if isinstance(reverb, dict) and reverb.get("on") and lib.has("df-room"):
            rack.append({"uid": "migrated-reverb", "plugin": "df-room", "on": True, "values": {
                "Dry Level": lib.norm("df-room", "Dry Level", 100),
                "Late Level": lib.norm("df-room", "Late Level", float(reverb.get("mix", 20))),
                "Decay": lib.norm("df-room", "Decay", float(reverb.get("decay", 1.2)))}})
        if isinstance(delay, dict) and delay.get("on") and lib.has("supermassive"):
            rack.append({"uid": "migrated-delay", "plugin": "supermassive", "on": True, "values": {
                "Mix": lib.norm("supermassive", "Mix", float(delay.get("mix", 18))),
                "Delay_Ms": lib.norm("supermassive", "Delay_Ms", float(delay.get("time", 320))),
                "Feedback": lib.norm("supermassive", "Feedback", float(delay.get("feedback", 30)))}})

    to_rack("rack", raw, raw.pop("reverb", None), raw.pop("delay", None))
    g = raw.get("guitar")
    if isinstance(g, dict):
        to_rack("rack", g, g.pop("reverb", None), g.pop("delay", None))
        if raw.get("route") != "guitar":
            g["on"] = False
    return raw


def sanitize(raw, lib):
    """Complete, clamped settings built from untrusted input (old versions are migrated first)."""
    raw = migrate(raw, lib)
    s = copy.deepcopy(DEFAULTS)
    raw = raw if isinstance(raw, dict) else {}
    s["enabled"] = bool(raw.get("enabled", True))
    s["mute"] = bool(raw.get("mute", False))
    if raw.get("route") in ROUTES:
        s["route"] = raw["route"]
    for key, (lo, hi) in LIMITS.items():
        src = raw
        for p in key.split("."):
            src = src.get(p) if isinstance(src, dict) else None
        v = _clamp_number(src, lo, hi)
        if v is None:
            continue
        target = s
        parts = key.split(".")
        for p in parts[:-1]:
            target = target[p]
        target[parts[-1]] = v
    for key in TOGGLES:
        src, target = raw, s
        for p in key.split("."):
            src = src.get(p) if isinstance(src, dict) else None
            target = target[p]
        if isinstance(src, dict) and "on" in src:
            target["on"] = bool(src["on"])
    g = raw.get("guitar") if isinstance(raw.get("guitar"), dict) else {}
    s["guitar"]["mute"] = bool(g.get("mute", False))
    if isinstance(raw.get("denoise"), dict) and raw["denoise"].get("strength") in DENOISE:
        s["denoise"]["strength"] = raw["denoise"]["strength"]
    s["rack"] = sanitize_rack(raw.get("rack"), lib)
    s["guitar"]["rack"] = sanitize_rack(g.get("rack"), lib)
    # the guitar switch and the "Mic 1 + Guitar 2" route are the same thing
    s["guitar"]["on"] = s["route"] == "guitar"
    return s


# ----------------------------------------------------------------------------- config lines
def _amp(db):
    return 10 ** (db / 20)


def vst_names_line(dll, params):
    args = " ".join(f'"{name}" {value:.7f}' for name, value in params.items())
    return f'VSTPlugin: Library "{dll}" {args}'


def gate_params(g):
    dry = 0.0 if g["range"] >= GATE_RANGE_MUTE else _amp(-g["range"])
    return {"Thresh": _amp(g["thresh"]), "Attack": g["attack"] / 500, "Hold": g["hold"] / 1000,
            "Release": g["release"] / 5000, "Pre-open": 0, "RMS size": 0, "Dry": dry, "Wet": 1 - dry}


def guitar_gate_params(g):
    # Between notes a guitar gate closes fully: pickup hum and buzz shouldn't be heard at all. It closes
    # 6 dB below where it opens (hysteresis), so a fading, beating note can't flap it open and shut.
    return {"Thresh": _amp(g["thresh"]), "Attack": 0.5 / 500, "Hold": 50 / 1000, "Release": 120 / 5000,
            "Pre-open": 0, "RMS size": 0, "Hystrsis": _amp(-6), "Dry": 0, "Wet": 1}


def kotelnikov_values(lib, c):
    n = lambda name, v: lib.norm("kotelnikov", name, v)
    return {"Threshold": n("Threshold", c["thresh"]), "Ratio": n("Ratio", c["ratio"]), "Attack": n("Attack", c["attack"]),
            "Release Peak": n("Release Peak", max(10, c["release"] * 0.5)), "Release RMS": n("Release RMS", c["release"]),
            "Soft Knee": n("Soft Knee", c["knee"]), "Makeup": n("Makeup", c["makeup"]), "Quality": n("Quality", "Precise")}


def deesser_values(lib, d):
    n = lambda name, v: lib.norm("nova", name, v)
    values = {f"Band {b} Active": n(f"Band {b} Active", "Off") for b in (1, 2, 3)}
    values.update({"Band 4 Active": n("Band 4 Active", "On"), "Band 4 Type": n("Band 4 Type", "Bell"),
                   "Band 4 Frequency": n("Band 4 Frequency", d["freq"]), "Band 4 Q": n("Band 4 Q", d["q"]),
                   "Band 4 Gain": n("Band 4 Gain", 0.0), "Band 4 Dyn": n("Band 4 Dyn", "On"),
                   "Band 4 Threshold": n("Band 4 Threshold", d["thresh"]), "Band 4 Ratio": n("Band 4 Ratio", 4.0),
                   "Band 4 Attack": n("Band 4 Attack", 1.0), "Band 4 Release": n("Band 4 Release", 60.0),
                   "EQ Auto Gain": n("EQ Auto Gain", "Off")})
    return values


def warmth_values(lib, w):
    # SlickEQ as a pure saturator: EQ flat, "Deep" output stage (low-end harmonics = weight and density),
    # auto gain keeps the level, "Live" quality adds no delay.
    n = lambda name, v: lib.norm("slickeq", name, v)
    return {"LOW Gain": n("LOW Gain", 0.0), "MID Gain": n("MID Gain", 0.0), "HIGH Gain": n("HIGH Gain", 0.0),
            "EQ Sat": n("EQ Sat", "Off"), "OUT Stage": n("OUT Stage", "Deep"), "OUT Drive": n("OUT Drive", w["drive"]),
            "Auto Gain": n("Auto Gain", "On"), "Quality": n("Quality", "Live"), "OUT Gain": n("OUT Gain", 0.0)}


def limiter_values(lib, lim):
    # LoudMax: Thresh lower = louder (drive into the limiter), Output = the ceiling; true-peak detection on.
    return {"Thresh": lib.norm("loudmax", "Thresh", -lim["drive"]), "Output": lib.norm("loudmax", "Output", lim["ceiling"]),
            "ISP Detection": lib.norm("loudmax", "ISP Detection", "ON")}


def rack_lines(lib, rack, plugin_dir):
    return [lib.line(slot["plugin"], slot["values"], plugin_dir) for slot in rack if slot["on"] and lib.usable(slot["plugin"])]


def voice_lines(s, lib, plugin_dir):
    lines = [f"Preamp: {s['gain']:.1f} dB"]
    if s["lowcut"]["on"]:
        f = s["lowcut"]["freq"]
        # two stacked high-passes = 24 dB/octave Butterworth
        lines += [f"Filter: ON HPQ Fc {f:g} Hz Q 0.54", f"Filter: ON HPQ Fc {f:g} Hz Q 1.31"]
    if s["denoise"]["on"] and lib.usable("rnnoise"):
        # RNNoise's model only works at 48 kHz; at any other rate Windows might switch to, skip it
        lines += ["If: sampleRate == 48000",
                  lib.line("rnnoise", {"VAD Threshold": DENOISE[s["denoise"]["strength"]],
                                       "VAD Grace Period (10ms per unit)": lib.norm("rnnoise", "VAD Grace Period (10ms per unit)", 20)},
                           plugin_dir),
                  "EndIf:"]
    if s["gate"]["on"] and lib.has_file(GATE_DLL):
        lines.append(vst_names_line(Path(plugin_dir) / GATE_DLL, gate_params(s["gate"])))
    for name, kind in BAND_FILTERS:
        b = s[name]
        if b["gain"]:
            lines.append(f"Filter: ON {kind} Fc {b['freq']:g} Hz Gain {b['gain']:.1f} dB Q {b['q']:.2f}")
    if s["hicut"]["on"]:
        lines.append(f"Filter: ON LPQ Fc {s['hicut']['freq']:g} Hz Q 0.71")
    if s["warmth"]["on"] and lib.usable("slickeq"):
        lines.append(lib.line("slickeq", warmth_values(lib, s["warmth"]), plugin_dir))
    if s["deesser"]["on"] and lib.usable("nova"):
        lines.append(lib.line("nova", deesser_values(lib, s["deesser"]), plugin_dir))
    if s["comp"]["on"] and lib.usable("kotelnikov"):
        lines.append(lib.line("kotelnikov", kotelnikov_values(lib, s["comp"]), plugin_dir))
    return lines + rack_lines(lib, s["rack"], plugin_dir)


def guitar_lines(g, lib, plugin_dir):
    f = g["lowcut"]
    lines = [f"Preamp: {g['gain']:.1f} dB", f"Filter: ON HPQ Fc {f:g} Hz Q 0.54", f"Filter: ON HPQ Fc {f:g} Hz Q 1.31"]
    if g["gate"]["on"] and lib.has_file(GATE_DLL):
        lines.append(vst_names_line(Path(plugin_dir) / GATE_DLL, guitar_gate_params(g["gate"])))
    for key, spec in (("bass", "LSC Fc 120 Hz Gain {:.1f} dB Q 0.70"), ("mid", "PK Fc 750 Hz Gain {:.1f} dB Q 0.80"),
                      ("treble", "HSC Fc 3200 Hz Gain {:.1f} dB Q 0.70")):
        if g[key]:
            lines.append("Filter: ON " + spec.format(g[key]))
    lines.append(f"Filter: ON LPQ Fc {g['tonecut']:g} Hz Q 0.71")
    sustain = g["comp"]["sustain"]
    if g["comp"]["on"] and sustain > 0 and lib.has_file(COMP_DLL):
        # ReaComp, not Kotelnikov: Kotelnikov looks 3.8 ms ahead, which a player feels; ReaComp adds no delay.
        thresh, ratio, makeup = -14 - 2.6 * sustain, 1.5 + 0.45 * sustain, 1.1 * sustain
        lines += [vst_names_line(Path(plugin_dir) / COMP_DLL, {
            "Thresh": _amp(thresh), "Ratio": (ratio - 1) / 99, "Attack": 15 / 500, "Release": 220 / 5000,
            "Knee": 6 / 24, "RMS size": 5 / 1000, "Pre-comp": 0, "AutoMkUp": 0, "Dry": 0, "Wet": 1}),
            f"Copy: R={makeup:.1f}dB*R"]
    return lines + rack_lines(lib, g["rack"], plugin_dir)


def guitar_latency_ms(s, lib):
    """Delay the guitar's plugins add (what a player feels on top of the monitor itself)."""
    if s["route"] != "guitar":
        return 0.0
    ids = [slot["plugin"] for slot in s["guitar"]["rack"] if slot["on"]]
    if s["limiter"]["on"]:
        ids.append("loudmax")
    total = 0.0
    for slot in s["guitar"]["rack"]:
        if slot["on"] and slot["plugin"] == "slickeq":  # SlickEQ's delay depends on its Quality setting
            q = lib.plugins["slickeq"]["byname"].get("Quality")
            pos = slot["values"].get("Quality", q["default"] if q else 0)
            near = min(q["choices"], key=lambda c: abs(c["value"] - pos))["text"] if q else "Full"
            total += {"Full": 3.81, "Eco": 0.33, "Live": 0.0}.get(near, 3.81)
            ids.remove("slickeq")
    return round(total + sum(lib.latency_ms(i) for i in ids if lib.has(i)), 1)


def render(s, lib, pattern, plugin_dir, bypass=False):
    """The whole mic.txt. All processing happens on the left channel and is copied right at the end."""
    active = s["enabled"] and not bypass
    lines = ["# Written by Mic Control. Changes made here by hand are overwritten.",
             "Stage: capture", f"Device: {pattern}", "Channel: all"]
    route = s["route"]
    limiter = [lib.line("loudmax", limiter_values(lib, s["limiter"]), plugin_dir)] if (
        active and s["limiter"]["on"] and lib.usable("loudmax")) else []

    if route == "stereo":
        if active:
            lines += voice_lines(s, lib, plugin_dir) + limiter
        if s["mute"]:
            lines.append("Copy: L=0.0 R=0.0")
        return "\n".join(lines) + "\n"

    if route == "guitar":
        g = s["guitar"]
        heard = not g["mute"]
        if active:
            lines += ["Channel: L", *voice_lines(s, lib, plugin_dir)]
            if heard:
                lines += ["Channel: R", *guitar_lines(g, lib, plugin_dir)]
        voice = 0.0 if s["mute"] else 1.0
        guitar = (_amp(g["level"]) if active else 1.0) if heard else 0.0
        lines += ["Channel: all", f"Copy: L={voice:.4f}*L+{guitar:.4f}*R"]
    else:
        lines += {"in1": [], "in2": ["Copy: L=R"], "mix": ["Copy: L=0.5*L+0.5*R"]}[route]
        if active:
            lines += ["Channel: L", *voice_lines(s, lib, plugin_dir)]
        if s["mute"]:
            lines += ["Channel: all", "Copy: L=0.0"]
    if limiter:
        lines += ["Channel: L", *limiter]
    lines += ["Channel: all", "Copy: R=L"]
    return "\n".join(lines) + "\n"


def chain_latency_ms(s, lib):
    """Delay the plugins add to the voice (shown in the app; Discord etc. never notice under ~30 ms)."""
    ids = []
    if s["denoise"]["on"]:
        ids.append("rnnoise")
    if s["deesser"]["on"]:
        ids.append("nova")
    if s["comp"]["on"]:
        ids.append("kotelnikov")
    ids += [slot["plugin"] for slot in s["rack"] if slot["on"]]
    if s["limiter"]["on"]:
        ids.append("loudmax")
    return round(sum(lib.latency_ms(i) for i in ids if lib.has(i)), 1)


